#!/usr/bin/env python3
"""Completeness of the database against Schabas (2013), document by document.

For every document the book reproduces (private references, eval/private/reference/):
  - is it in the database, and if not, why (not harvested, unavailable at the UN, not OCR'd)?
  - how much of the book's text of it is in ours? A sentence of the book counts as found
    when at least half of its three-word sequences occur in our text of that document
    (OCR errors break some, so "half" is lenient on purpose);
  - which of the book's pages (the original UN page numbers) are mostly missing?
The report (docs/overnight/completeness_udhr.md) holds only symbols and numbers, never the
book's text, so it can be committed.

Usage: python3 eval/completeness.py
"""
from __future__ import annotations

import json
import re
import sys
import unicodedata
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pipeline"))
from common import safe_name  # noqa: E402

REF = ROOT / "eval" / "private" / "reference"
SEG = ROOT / "data" / "segments"
OUT = ROOT / "docs" / "overnight" / "completeness_udhr.md"
OUT_JSON = ROOT / "eval" / "completeness_udhr.json"


def words(text: str) -> list[str]:
    t = unicodedata.normalize("NFKC", text).lower()
    t = re.sub(r"(\w)-\s*\n\s*(\w)", r"\1\2", t)
    return re.findall(r"[a-z0-9]+", t)


def shingles(ws: list[str]) -> set[tuple[str, str, str]]:
    return {tuple(ws[i:i + 3]) for i in range(len(ws) - 2)}


def sentences(text: str) -> list[str]:
    # the book's own document header (symbol, date, "Original Text: French") is not UN text
    text = re.sub(r"\A\s*\S+/\S+\s*\n[^\n]*\d{4}\s*\n(?:\s*Original Text:[^\n]*\n)?", "", text)
    text = re.sub(r"\[[^\]]{0,120}\]", " ", text)
    return [s for s in re.split(r"(?<=[.;:?!])\s+|\s*(?:…|\. \. \.)\s*", text) if len(s.split()) >= 6]


def harvest_status() -> dict[str, str]:
    st = {}
    for p in sorted((ROOT / "data" / "manifest").glob("harvest_*.json")):
        for sym, e in json.loads(p.read_text()).items():
            if st.get(sym) != "ok":
                st[sym] = e.get("status", "?")
    return st


def main() -> int:
    hs = harvest_status()
    rows = []
    for ref_path in sorted(REF.glob("*.json")):
        ref = json.loads(ref_path.read_text())
        sym = ref["symbol"]
        seg_path = SEG / f"{safe_name(sym)}.vote.json"
        if not seg_path.exists():
            reason = {"ok": "harvested, not yet OCR'd/segmented", "ods_unavailable": "not available from ODS"}.get(
                hs.get(sym), "not in any manifest" if sym not in hs else hs[sym])
            rows.append({"symbol": sym, "status": "missing", "reason": reason})
            continue
        ours = shingles(words(" ".join(s["text"] for s in json.loads(seg_path.read_text()))))
        per_page, found, total = {}, 0, 0
        for page, text in ref["pages"].items():
            ss = sentences(text)
            f = 0
            for snt in ss:
                sh = shingles(words(snt))
                if sh and len(sh & ours) / len(sh) >= 0.5:
                    f += 1
            per_page[page] = (f, len(ss))
            found += f
            total += len(ss)
        cov = found / total if total else None
        weak = [p for p, (f, n) in per_page.items() if n >= 3 and f / n < 0.5]
        # nothing of a long excerpt found in a text of fair size: probably a different document
        # under the same symbol (ECOSOC's 1946 E/SR numbers restart with each session)
        mismatch = cov is not None and cov < 0.05 and total >= 10 and len(ours) > 2000
        rows.append({"symbol": sym, "status": "in_db", "coverage": round(cov, 3) if cov is not None else None,
                     "sentences": total, "weak_pages": weak, "symbol_mismatch": mismatch})
    OUT_JSON.write_text(json.dumps(rows, indent=1), encoding="utf-8")

    in_db = [r for r in rows if r["status"] == "in_db" and r["coverage"] is not None]
    missing = [r for r in rows if r["status"] == "missing"]
    tot_s = sum(r["sentences"] for r in in_db)
    wcov = sum(r["coverage"] * r["sentences"] for r in in_db) / tot_s if tot_s else 0
    bands = Counter("≥ 95%" if r["coverage"] >= 0.95 else "80–95%" if r["coverage"] >= 0.8 else
                    "50–80%" if r["coverage"] >= 0.5 else "< 50%" for r in in_db)
    reasons = Counter(r["reason"] for r in missing)
    lines = [
        "# UDHR completeness against Schabas (2013)", "",
        "Generated by `eval/completeness.py`. Only UN symbols and counts are shown; the book's text stays private.", "",
        f"- Documents the book reproduces: **{len(rows)}**",
        f"- In the database: **{len(in_db)}**; missing: **{len(missing)}**",
        f"- Share of the book's sentences found in our text (documents in the DB, weighted by length): **{wcov:.1%}**",
        "", "## Coverage of documents in the database", "",
        "| Coverage | Documents |", "|---|---|",
        *[f"| {b} | {bands.get(b, 0)} |" for b in ("≥ 95%", "80–95%", "50–80%", "< 50%")],
        "", "## Missing documents, by reason", "",
        "| Reason | Documents |", "|---|---|",
        *[f"| {k} | {v} |" for k, v in reasons.most_common()],
        "", "## Probable symbol mismatches", "",
        "The UN copy under the symbol holds none of the book's text of it (for instance ECOSOC 1946 records, "
        "whose E/SR numbers restart with each session): " +
        (", ".join(r["symbol"] for r in in_db if r.get("symbol_mismatch")) or "none") + ".",
        "", "## Weakest documents in the database (coverage < 80%)", "",
        "| Symbol | Coverage | Sentences | Pages with most text missing |", "|---|---|---|---|",
        *[f"| {r['symbol']} | {r['coverage']:.0%} | {r['sentences']} | {', '.join(r['weak_pages'][:12])} |"
          for r in sorted(in_db, key=lambda r: r["coverage"]) if r["coverage"] < 0.8][:60],
        "", "## Missing documents", "",
        ", ".join(f"{r['symbol']} ({r['reason']})" for r in missing[:200]),
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} documents; in DB {len(in_db)}, missing {len(missing)}; sentence coverage {wcov:.1%}", file=sys.stderr)
    print(dict(bands), dict(reasons), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
